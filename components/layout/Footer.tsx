/** Uses next/link for internal routes so basePath is applied on GitHub Pages. */
function FooterLink({ href, label }: { href: string; label: string }) {
  const className =
    "inline-flex min-h-[28px] items-center text-sm text-[var(--text-secondary)] transition-colors hover:text-[var(--text-primary)] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[var(--color-info)]";

  if (href.startsWith("/")) {
    return (
      <Link href={href} className={className}>
        {label}
      </Link>
    );
  }

  return (
    <a href={href} className={className}>
      {label}
    </a>
  );
}

